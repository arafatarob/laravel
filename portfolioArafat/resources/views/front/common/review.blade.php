<script>
  document.addEventListener('DOMContentLoaded', () => {
    const track = document.getElementById('sliderTrack');
    const cards = track.querySelectorAll('.rev-card');
    const dotsEl = document.getElementById('dots');
    const prevBtn = document.getElementById('prevBtn');
    const nextBtn = document.getElementById('nextBtn');
    
    if (!track || cards.length === 0) return; // Error handling

    const total = cards.length;
    const visible = 3;
    const maxIndex = total - visible;
    let current = 0;

    // Dots create kora
    dotsEl.innerHTML = ''; // Agey kichu thakle clear korbe
    for (let i = 0; i <= maxIndex; i++) {
        const d = document.createElement('div');
        d.className = 'dot' + (i === 0 ? ' active' : '');
        d.addEventListener('click', () => goTo(i));
        dotsEl.appendChild(d);
    }

    function goTo(idx) {
        current = idx;
        // Jhamela erate loop thik kora
        if (current > maxIndex) current = 0;
        if (current < 0) current = maxIndex;

        const cardW = cards[0].offsetWidth + 20; // 20 holo margin/gap
        track.style.transform = `translateX(-${current * cardW}px)`;
        
        // Dots update
        const dots = dotsEl.querySelectorAll('.dot');
        dots.forEach((d, i) => d.classList.toggle('active', i === current));
    }

    // Button Click Event
    if (prevBtn) prevBtn.onclick = () => goTo(current - 1);
    if (nextBtn) nextBtn.onclick = () => goTo(current + 1);

    // Auto Slider logic
    let autoTimer = setInterval(() => goTo(current + 1), 3500);

    const restartTimer = () => {
        clearInterval(autoTimer);
        autoTimer = setInterval(() => goTo(current + 1), 3500);
    };

    track.addEventListener('mouseenter', () => clearInterval(autoTimer));
    track.addEventListener('mouseleave', restartTimer);
});
</script>