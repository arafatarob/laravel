    <script>
        document.addEventListener("DOMContentLoaded", function () {
            // Tabs
            let lead = document.getElementById("lead");
            let thumbnail = document.getElementById("thumbnail");
            let ytResult = document.getElementById("ytResult");

            // Galleries
            let leadGallery = document.getElementById("leadGallery");
            let thumbnailGallery = document.getElementById("thumbnailGallery");
            let youtubeResult = document.getElementById("youtubeResult");

            // All tabs for active toggle
            const tabs = [lead, thumbnail, ytResult];

            function setActiveTab(activeTab, activeGallery) {
                // Hide all galleries
                leadGallery.style.display = "none";
                thumbnailGallery.style.display = "none";
                youtubeResult.style.display = "none";

                // Remove 'active' class from all tabs
                tabs.forEach(tab => tab.classList.remove("active"));

                // Show selected gallery
                activeGallery.style.display = "block";

                // Add 'active' class to selected tab
                activeTab.classList.add("active");
            }

            // Event listeners
            lead.addEventListener("click", function () {
                setActiveTab(lead, leadGallery);
            });

            thumbnail.addEventListener("click", function () {
                setActiveTab(thumbnail, thumbnailGallery);
            });

            ytResult.addEventListener("click", function () {
                setActiveTab(ytResult, youtubeResult);
            });

            // Default: lead active
            setActiveTab(lead, leadGallery);
        });
    </script>